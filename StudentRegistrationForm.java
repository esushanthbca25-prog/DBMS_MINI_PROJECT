    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
    String url = "jdbc:mysql://localhost:3306/student_db";
    String user = "root";
    String password = "ChooseYourOwnPassword123!";

    java.sql.Connection con =
        java.sql.DriverManager.getConnection(url, user, password);

    String sql = "INSERT INTO students "
        + "(student_id, name, email, course, semester) "
        + "VALUES (?, ?, ?, ?, ?)";

    java.sql.PreparedStatement ps = con.prepareStatement(sql);

    ps.setInt(1, Integer.parseInt(txtStudentId.getText().trim()));
    ps.setString(2, txtName.getText().trim());
    ps.setString(3, txtEmail.getText().trim());
    ps.setString(4, txtCourse.getText().trim());
    ps.setInt(5, Integer.parseInt(txtSemester.getText().trim()));

    ps.executeUpdate();

    javax.swing.JOptionPane.showMessageDialog(
        this, "Student registered successfully!");

    ps.close();
    con.close();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error: " + e.getMessage());
}
    }//GEN-LAST:event_jButton1ActionPerformed

